use std::fs;
use std::path::PathBuf;

fn main() {
    println!("cargo:rerun-if-changed=icons/icon.ico");
    tauri_build::build();
    generate_migrations();
}

/// Emits a `migrations_gen.rs` file containing every `migrations/*.sql` file,
/// sorted by filename, so migrations are compiled into the binary and remain
/// available in packaged builds (where the `migrations/` directory is absent).
fn generate_migrations() {
    let manifest_dir = PathBuf::from(
        std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is not set"),
    );
    let migrations_dir = manifest_dir.join("migrations");

    println!("cargo:rerun-if-changed={}", migrations_dir.display());

    let mut entries: Vec<PathBuf> = match fs::read_dir(&migrations_dir) {
        Ok(dir) => dir
            .filter_map(|entry| entry.ok().map(|entry| entry.path()))
            .filter(|path| path.extension().and_then(|ext| ext.to_str()) == Some("sql"))
            .collect(),
        Err(_) => Vec::new(),
    };
    entries.sort();

    let mut generated = String::from(
        "// @generated by build.rs - do not edit by hand.\n\
         pub const MIGRATIONS: &[(&str, &str)] = &[\n",
    );
    for path in &entries {
        let name = path
            .file_name()
            .map(|name| name.to_string_lossy().into_owned())
            .unwrap_or_default();
        let absolute = path.to_string_lossy().into_owned();
        generated.push_str(&format!(
            "    ({:?}, include_str!(r#\"{}\"#)),\n",
            name, absolute
        ));
    }
    generated.push_str("];\n");

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR is not set"));
    fs::write(out_dir.join("migrations_gen.rs"), generated)
        .expect("failed to write migrations_gen.rs");
}
